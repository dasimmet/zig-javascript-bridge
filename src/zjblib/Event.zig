// 7. Public functions
/// Wraps a non-null JS Event handle as an Event view.
pub fn fromHandle(handle: zjb.Handle) Event {
    std.debug.assert(!handle.isNull());
    std.debug.assert(@backingInt(handle) != 0);
    return .{ .handle = handle };
}

/// Returns true if the underlying JS handle is null or undefined.
pub fn isNull(self: Event) bool {
    return self.handle.isNull();
}

/// Cancels the event if it is cancelable, stopping default browser action.
/// https://developer.mozilla.org/en-US/docs/Web/API/Event/preventDefault
pub fn preventDefault(self: Event) void {
    std.debug.assert(!self.handle.isNull());
    std.debug.assert(@backingInt(self.handle) != 0);
    const prevent_fn = self.handle.get("preventDefault", zjb.Handle);
    if (!prevent_fn.isNull()) {
        defer prevent_fn.release();
        prevent_fn.call("apply", .{ self.handle, zjb.Handle.null }, void);
    }
}

/// Prevents further propagation of the event in capturing/bubbling phases.
/// https://developer.mozilla.org/en-US/docs/Web/API/Event/stopPropagation

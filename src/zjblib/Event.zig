/// Maps a DOM event name at compile time to its typed Event wrapper struct.
pub fn EventFor(comptime event_name: []const u8) type {
    const mappings = .{
        .{ "keydown", KeyboardEvent },
        .{ "keyup", KeyboardEvent },
        .{ "keypress", KeyboardEvent },
        .{ "paste", ClipboardEvent },
        .{ "copy", ClipboardEvent },
        .{ "cut", ClipboardEvent },
        .{ "mousedown", MouseEvent },
        .{ "mousemove", MouseEvent },
        .{ "mouseup", MouseEvent },
        .{ "mouseenter", MouseEvent },
        .{ "mouseleave", MouseEvent },
        .{ "mouseover", MouseEvent },
        .{ "mouseout", MouseEvent },
        .{ "click", PointerEvent },
        .{ "dblclick", PointerEvent },
        .{ "contextmenu", PointerEvent },
        .{ "wheel", WheelEvent },
        .{ "input", InputEvent },
        .{ "beforeinput", InputEvent },
        .{ "submit", SubmitEvent },
        .{ "hashchange", HashChangeEvent },
        .{ "change", MediaQueryListEvent },
        .{ "touchstart", TouchEvent },
        .{ "touchmove", TouchEvent },
        .{ "touchend", TouchEvent },
        .{ "touchcancel", TouchEvent },
        .{ "focus", FocusEvent },
        .{ "blur", FocusEvent },
        .{ "popstate", PopStateEvent },
        .{ "beforeinstallprompt", BeforeInstallPromptEvent },
    };
    inline for (mappings) |entry| {
        if (std.mem.eql(u8, event_name, entry[0])) return entry[1];
    }
    return Event;
}
